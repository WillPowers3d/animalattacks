const JUNK_SUFFIXES = [
  ".facebook.com",
  ".twitter.com",
  ".instagram.com",
  ".youtube.com",
  ".wikipedia.org",
  ".google.com",
  ".apple.com",
];

export function isNationalOrJunkHost(host: string): boolean {
  const h = host.toLowerCase().replace(/^www\./, "");
  if (NATIONAL_OR_JUNK_HOSTS.has(h)) return true;
  if (JUNK_SUFFIXES.some((s) => h.endsWith(s))) return true;
  if (h.endsWith(".gov") || h.endsWith(".mil")) return true;
  return false;
}
